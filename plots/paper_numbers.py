"""
Every number quoted in the paper, written as LaTeX so the text cannot drift
from the data.

    python plots/paper_numbers.py --bench data/psf_bench.npy \
        --ngauss data/psf_bench_ngauss.npy --shear data/shear \
        --outdir figures

writes
    figures/numbers.tex      \\valdef{key}{value} for each statistic; the
                             paper reads them with \\val{key}, and a missing
                             key prints as a red ??key
    figures/table_speed.tex  the rows of Table 1
    figures/table_shear.tex  the rows of Table 2
    figures/numbers.txt      the same statistics as plain text, for review
"""
import argparse
import json
import os
import numpy as np
import style

TOLS = {5: 1.0e-5, 6: 1.0e-6, 8: 1.0e-8}
AGREE = 1.0e-3   # |dT/T| and |de| below which two fits are "the same"


def fmt(x, nd=2):
    """compact number formatting for prose"""
    if x is None or not np.isfinite(x):
        return 'nan'
    ax = abs(x)
    if ax != 0 and (ax < 1e-2 or ax >= 1e5):
        m, e = ('%.*e' % (nd - 1, x)).split('e')
        return r'%s\times10^{%d}' % (m, int(e))
    if ax >= 100:
        return '%d' % round(x)
    return '%.*f' % (nd if ax < 10 else nd - 1, x)


class Numbers(object):
    def __init__(self):
        self.vals = {}

    def __setitem__(self, k, v):
        self.vals[k] = v

    def write(self, outdir):
        with open(os.path.join(outdir, 'numbers.tex'), 'w') as f:
            f.write('%% generated by plots/paper_numbers.py; do not edit\n')
            for k, v in sorted(self.vals.items()):
                s = v if isinstance(v, str) else fmt(v)
                f.write('\\valdef{%s}{%s}\n' % (k, s))
        with open(os.path.join(outdir, 'numbers.txt'), 'w') as f:
            for k, v in sorted(self.vals.items()):
                f.write('%-45s %s\n' % (k, v))


def bench_numbers(N, d, outdir):
    d = d[d['ngauss'] == 5]
    rows = []
    for t, tol in TOLS.items():
        for fam in [f for f in style.FAMILIES if f in set(d['family'])]:
            sel = (d['family'] == fam) & (d['tol'] == tol)
            a = d[sel & ~d['accelerate']]
            b = d[sel & d['accelerate']]
            # pair by PSF
            a = a[np.argsort(a['ipsf'])]
            b = b[np.argsort(b['ipsf'])]
            assert np.all(a['ipsf'] == b['ipsf'])
            k = '%s-tol%d-' % (fam, t)
            r = a['numiter'] / b['numiter']
            N[k + 'npsf'] = '%d' % len(a)
            for name, x in (('em', a), ('sq', b)):
                n = x['numiter']
                N[k + name + '-median'] = np.median(n)
                N[k + name + '-mean'] = n.mean()
                N[k + name + '-std'] = n.std(ddof=1)
                N[k + name + '-max'] = '%d' % n.max()
                N[k + name + '-maxiterhits'] = '%d' % x['maxiter_hit'].sum()
                N[k + name + '-fp-median'] = np.nanmedian(x['fp'])
            N[k + 'speedup-median'] = np.median(r)
            N[k + 'speedup-mean'] = r.mean()
            N[k + 'speedup-std'] = r.std(ddof=1)
            N[k + 'speedup-p10'] = np.percentile(r, 10)
            N[k + 'speedup-p90'] = np.percentile(r, 90)
            N[k + 'slower-pct'] = '%d' % round(100 * np.mean(r < 1))
            N[k + 'timeratio-median'] = np.median(a['time'] / b['time'])
            # do the two runners reach the same optimum?
            same = ((np.abs(a['T'] - b['T']) / a['T'] < AGREE)
                    & (np.hypot(a['e1'] - b['e1'], a['e2'] - b['e2'])
                       < AGREE))
            N[k + 'agree-pct'] = '%d' % round(100 * np.mean(same))
            diff = ~same
            if diff.any():
                better = b['loglike'][diff] > a['loglike'][diff]
                N[k + 'differ-sqbetter-pct'] = '%d' % round(
                    100 * np.mean(better))
            if t in (6, 8):
                rows.append((t, fam, a, b, r))

    # table rows, grouped by tolerance
    lines = []
    for t in (6, 8):
        lines.append(r'\multicolumn{8}{l}{\texttt{tol}\,$=10^{-%d}$%s}\\'
                     % (t, ' (SuperBIT)' if t == 6 else ''))
        for tt, fam, a, b, r in rows:
            if tt != t:
                continue
            lines.append(
                r'\quad %s & %d & %d & %d $\pm$ %d & %d & %d $\pm$ %d & '
                r'%.1f & %d \\' % (
                    style.FAMILY_LABELS[fam], len(a),
                    np.median(a['numiter']), a['numiter'].mean(),
                    a['numiter'].std(ddof=1), np.median(b['numiter']),
                    b['numiter'].mean(), b['numiter'].std(ddof=1),
                    np.median(r), round(100 * np.mean(r < 1))))
    head = [r'\begin{tabular}{l r rr rr rr}', r'\toprule',
            r' & & \multicolumn{2}{c}{EM} & \multicolumn{2}{c}{SQUAREM}'
            r' & & \\',
            r'\cmidrule(lr){3-4}\cmidrule(lr){5-6}',
            r'PSF source & $N_{\rm PSF}$ & median & mean $\pm$ std & median'
            r' & mean $\pm$ std & speedup & slower (\%) \\', r'\midrule']
    with open(os.path.join(outdir, 'table_speed.tex'), 'w') as f:
        f.write('\n'.join(head + lines + [r'\bottomrule', r'\end{tabular}'])
                + '\n')


def ngauss_numbers(N, d):
    d = d[d['tol'] == 1.0e-6]
    for fam in [f for f in style.FAMILIES if f in set(d['family'])]:
        for ng in sorted(set(d['ngauss'])):
            for acc, name in ((False, 'em'), (True, 'sq')):
                x = d[(d['family'] == fam) & (d['ngauss'] == ng)
                      & (d['accelerate'] == acc)]
                if len(x) == 0:
                    continue
                k = '%s-ng%d-%s-' % (fam, ng, name)
                N[k + 'npsf'] = '%d' % len(x)
                N[k + 'dT-median'] = np.nanmedian(np.abs(x['dT_admom']))
                N[k + 'de-median'] = np.nanmedian(x['de_admom'])
                N[k + 'resid-median'] = np.nanmedian(x['resid'])
                N[k + 'iter-median'] = np.median(x['numiter'])


SHEAR_KEYS = ('m', 'c1', 'c2', 'alpha', 'R11')
COST_KEYS = ('psf_time_frac', 'psf_iter_per_fit', 'time_per_object')


def shear_numbers(N, shear_dir, outdir):
    lines = []
    for fam in style.FAMILIES:
        f = os.path.join(shear_dir, fam, 'summary.json')
        if not os.path.exists(f):
            continue
        with open(f) as fh:
            s = json.load(fh)
        N['%s-shear-ngal' % fam] = '%d' % s['ngal']
        for arm, v in s['arms'].items():
            k = '%s-%s-' % (fam, arm.replace('_', ''))
            for q in SHEAR_KEYS:
                N[k + q] = v[q]
                N[k + q + '-err'] = v[q + '_err']
                if 'd' + q in v:
                    N[k + 'd' + q] = v['d' + q]
                    N[k + 'd' + q + '-err'] = v['d' + q + '_err']
            for q in COST_KEYS:
                for st in ('mean', 'median', 'std'):
                    if '%s_%s' % (q, st) not in v:
                        continue
                    x = v['%s_%s' % (q, st)]
                    if q == 'psf_time_frac':
                        # quoted as a percentage in the text
                        x = r'%.1f\%%' % (100 * x)
                    N['%s%s-%s' % (k, q.replace('_', ''), st)] = x
            if 'psf_maxiter_frac' in v:
                N[k + 'maxiterfrac'] = v['psf_maxiter_frac']
            if arm == 'em5_converged':
                continue
            lines.append(
                r'%s & %s & $%s \pm %s$ & $%s \pm %s$ & $%s \pm %s$ & '
                r'$%s \pm %s$ \\' % (
                    style.FAMILY_LABELS[fam], arm.replace('_', r'\_'),
                    fmt(v['dm']), fmt(v['dm_err']),
                    fmt(v['dc1']), fmt(v['dc1_err']),
                    fmt(v['dalpha']), fmt(v['dalpha_err']),
                    fmt(v['dR11']), fmt(v['dR11_err'])))
    head = [r'\begin{tabular}{ll rrrr}', r'\toprule',
            r'PSF source & arm & $\Delta m$ & $\Delta c_1$ & $\Delta\alpha$'
            r' & $\Delta R_{11}$ \\', r'\midrule']
    with open(os.path.join(outdir, 'table_shear.tex'), 'w') as f:
        f.write('\n'.join(head + lines + [r'\bottomrule', r'\end{tabular}'])
                + '\n')


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--bench')
    p.add_argument('--ngauss')
    p.add_argument('--shear')
    p.add_argument('--outdir', required=True)
    args = p.parse_args()

    N = Numbers()
    if args.bench and os.path.exists(args.bench):
        bench_numbers(N, np.load(args.bench), args.outdir)
    if args.ngauss and os.path.exists(args.ngauss):
        ngauss_numbers(N, np.load(args.ngauss))
    if args.shear and os.path.isdir(args.shear):
        shear_numbers(N, args.shear, args.outdir)
    N.write(args.outdir)
    print('%d numbers written' % len(N.vals))


if __name__ == '__main__':
    main()
